/**
 * Phase 3 — Custom Testing: real requirement -> AI strategy -> test cases
 * -> existing Test Case Generator / execution pipeline.
 *
 * Replaces the previous truthful "not implemented" placeholder (FE-11 —
 * see git history for that version's own doc comment). Re-verified against
 * the current backend route table before writing this: no custom-test-suite
 * entity exists (unchanged), but `POST .../custom-testing/generate`
 * (`custom_testing.rs`) now exists for real, reusing the exact central AI
 * router (`AiTask::RequirementAnalysis`, newly wired this phase;
 * `AiTask::TestCaseGeneration` reused byte-for-byte from the Test Case
 * Generator's own `ai_generation::generate_test_cases`) — no duplicate
 * router, no duplicate generator.
 *
 * Deliberately does NOT reimplement save/validate/approve/handoff/compile
 * logic: once real cases are generated, "Continue to Test Case Generator"
 * hands off into the exact same `AIQAContext.activeGenerationSession` +
 * `/test-generator` route the Test Case Generator's own AI drafts already
 * use (see `TestCaseGeneratorPage.tsx`'s own `handleTriggerGenerate`) — the
 * entire existing persistence/review/execution pipeline applies with zero
 * duplicated code. The `Project` resource has no module/feature metadata
 * (`store.rs::Project` — confirmed, id/name/description/timestamps only),
 * so "scope" here is real, honestly-labeled user-provided free text, never
 * a fabricated project module list.
 */
import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Sliders, AlertTriangle, CheckCircle2, XCircle, Sparkles, ArrowRight, Target, ShieldAlert, ListChecks, Lightbulb, ClipboardList, Info } from 'lucide-react';
import { SectionHeader } from '../common/SectionHeader';
import { EmptyState } from '../common/EmptyState';
import { SkillsAndMcpPanel } from '../test-generator/SkillsAndMcpPanel';
import { useSkillSelection } from '../../hooks/useSkillSelection';
import { DEFAULT_SELECTED_SKILL_IDS } from '../../services/skillRegistry';
import { useProject } from '../../context/ProjectContext';
import { useAIQA } from '../../context/AIQAContext';
import { ApiError, aiqaApi } from '../../services/aiqaApi';
import type { CustomTestingAnalysis, CustomTestingGenerateResponse, GeneratedTestCaseDraft } from '../../types/contract';
import type { GeneratedTestCase } from '../../types';

type AnalysisStatus =
  | 'IDLE'
  | 'VALIDATION_FAILED'
  | 'NO_ACTIVE_PROJECT'
  | 'ANALYZING'
  | 'GENERATED'
  | 'NO_GENERATED_TEST_CASES'
  | 'AI_UNAVAILABLE'
  | 'GENERATION_FAILED'
  | 'PROJECT_ACCESS_DENIED'
  | 'ANALYSIS_FAILED';

/** Mirrors `TestCaseGeneratorPage.tsx::aiDraftToDisplay` in spirit (same
 *  honest, non-fabricated field-mapping principles) but adapted for this
 *  page's own real inputs (`scope`/`analysis`) instead of documents/app
 *  sources, which this page has no concept of. */
function customDraftToDisplay(
  draft: GeneratedTestCaseDraft,
  index: number,
  ctx: { requirementText: string; scope: string; provider: string; model: string },
): GeneratedTestCase {
  const tcId = `CT-${(index + 1).toString().padStart(3, '0')}`;
  const aiAnalysis = `Generated by ${ctx.provider}/${ctx.model} from a Custom Testing requirement${
    ctx.scope ? ` (scope: ${ctx.scope})` : ''
  } — evidence: ${draft.evidence}${draft.source_reference ? `, cites: "${draft.source_reference}"` : ''}.`;

  return {
    id: tcId,
    title: draft.title,
    description: `Custom-testing-generated ${draft.category} test case (evidence: ${draft.evidence}).`,
    category: draft.category,
    priority: draft.priority as GeneratedTestCase['priority'],
    severity: draft.severity as GeneratedTestCase['severity'],
    requirementReference: draft.source_reference ?? undefined,
    sourceRequirement: ctx.requirementText,
    traceability: {
      sourceDoc: ctx.scope ? `Custom scope: ${ctx.scope}` : 'Requirement text only (no scope given)',
      requirementRef: draft.source_reference ?? `Not cited (${draft.evidence})`,
      requirementText: ctx.requirementText,
      aiAnalysis,
      testCaseId: tcId,
      testCategory: draft.category,
      executionTarget: 'Not yet assigned — assigned at execution handoff',
      evidencePolicy: 'Not yet captured — captured at execution handoff',
      reportMapping: 'Not yet mapped',
    },
    preconditions: draft.preconditions,
    testData: JSON.stringify({ evidence: draft.evidence, source_reference: draft.source_reference, source: 'custom_testing' }, null, 2),
    steps: draft.steps.map((s, i) => ({ stepNumber: i + 1, action: s.action, expectedResult: s.expected_result })),
    expectedResult: draft.expected_result,
    assertions: [draft.expected_result],
    riskFactor: draft.priority === 'CRITICAL' ? 'HIGH' : draft.priority === 'HIGH' ? 'MEDIUM' : 'LOW',
    status: 'PENDING_REVIEW',
    suggestedTags: [draft.category.toLowerCase().replace(/\s+/g, '-'), draft.evidence, 'custom-testing'],
    generatedAt: new Date().toISOString(),
  };
}

export const CustomTestingPage: React.FC = () => {
  const navigate = useNavigate();
  const { selectedProjectId: realProjectId, selectedProject } = useProject();
  const { setActiveGenerationSession } = useAIQA();

  const [scope, setScope] = useState('');
  const [requirementText, setRequirementText] = useState('');
  const { skills, selectedSkillIds, toggleSkill, addCustomSkill } = useSkillSelection(DEFAULT_SELECTED_SKILL_IDS);

  const [status, setStatus] = useState<AnalysisStatus>('IDLE');
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [result, setResult] = useState<CustomTestingGenerateResponse | null>(null);
  const [lastRequirementText, setLastRequirementText] = useState('');
  const [lastScope, setLastScope] = useState('');

  const isAnalyzing = status === 'ANALYZING';

  const handleAddRecommendedSkill = (name: string) => {
    const existing = skills.find((s) => s.name.toLowerCase() === name.toLowerCase());
    if (existing) {
      if (!selectedSkillIds.includes(existing.id)) toggleSkill(existing.id);
      return;
    }
    addCustomSkill({ name, description: `AI-recommended focus area for this custom testing requirement: "${name}".` });
  };

  const handleAnalyzeAndGenerate = async () => {
    if (!realProjectId) {
      setStatus('NO_ACTIVE_PROJECT');
      setErrorMessage('Select a project before creating a custom testing request.');
      return;
    }
    const trimmed = requirementText.trim();
    if (!trimmed) {
      setStatus('VALIDATION_FAILED');
      setErrorMessage('Enter a custom testing requirement before analyzing.');
      return;
    }

    setErrorMessage(null);
    setResult(null);
    setStatus('ANALYZING');

    const requestSkills = selectedSkillIds
      .map((id) => skills.find((s) => s.id === id))
      .filter((s): s is (typeof skills)[number] => Boolean(s))
      .map((s) => ({ id: s.id, name: s.name, description: s.description }));

    try {
      const response = await aiqaApi.customTesting.generate(realProjectId, {
        requirement_text: trimmed,
        scope: scope.trim() || undefined,
        skills: requestSkills,
      });
      setResult(response);
      setLastRequirementText(trimmed);
      setLastScope(scope.trim());

      if (response.generation_source === 'REAL_AI' && response.test_cases.length > 0) {
        setStatus('GENERATED');
      } else if (response.generation_source === 'REAL_AI') {
        setStatus('NO_GENERATED_TEST_CASES');
        setErrorMessage('The AI model produced a real strategy, but no candidate test case passed quality/traceability validation. Try more specific requirement text.');
      } else if (response.analysis) {
        setStatus('GENERATION_FAILED');
        setErrorMessage(response.failure_reason || 'A real strategy was produced, but test case generation failed.');
      } else {
        setStatus('AI_UNAVAILABLE');
        setErrorMessage(response.failure_reason || 'No AI provider is currently available for custom testing analysis.');
      }
    } catch (err) {
      setResult(null);
      if (err instanceof ApiError && err.kind === 'forbidden') {
        setStatus('PROJECT_ACCESS_DENIED');
        setErrorMessage(err.message);
      } else {
        setStatus('ANALYSIS_FAILED');
        setErrorMessage(err instanceof ApiError ? err.message : 'Custom testing analysis failed.');
      }
    }
  };

  const handleContinueToTestCaseGenerator = () => {
    if (!result || result.test_cases.length === 0) return;
    const mapped = result.test_cases.map((draft, i) =>
      customDraftToDisplay(draft, i, { requirementText: lastRequirementText, scope: lastScope, provider: result.provider ?? 'an AI provider', model: result.model ?? 'an unreported model' }),
    );
    setActiveGenerationSession({
      id: `custom-${Date.now()}`,
      requirementText: lastScope ? `${lastRequirementText}\n\nTesting scope/module (user-provided): ${lastScope}` : lastRequirementText,
      specType: 'NATURAL_LANGUAGE',
      currentStep: 'GENERATED_CASES',
      generationState: 'COMPLETED',
      depth: 'STANDARD',
      generatedCases: mapped,
      createdAt: new Date().toISOString(),
      selectedSkillIds,
    });
    navigate('/test-generator');
  };

  const analysis: CustomTestingAnalysis | null = result?.analysis ?? null;

  return (
    <div id="custom-testing-page" className="space-y-4 animate-in fade-in duration-150">
      <SectionHeader
        title="Custom Testing"
        subtitle="Describe what you want tested in your own words — a real AI strategy and test cases are generated from your exact requirement, then reviewed/executed through the existing Test Case Generator pipeline."
        badge={status === 'GENERATED' ? 'GENERATED' : undefined}
        icon={Sliders}
      />

      {!realProjectId ? (
        <EmptyState
          icon={AlertTriangle}
          badge="NO ACTIVE PROJECT"
          title="Select a project before creating a custom testing request"
          description="Custom Testing requests are project-scoped, same as the Test Case Generator — choose a project from the selector before entering a requirement."
          actionLabel="Go to Dashboard"
          onAction={() => navigate('/dashboard')}
        />
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-4">
          <div className="lg:col-span-9 space-y-4">
            <div className="p-4 rounded-lg bg-[#0B1120] border border-slate-800 shadow-sm space-y-3">
              <div className="flex items-center justify-between">
                <span className="text-xs font-mono text-slate-400">Project Context</span>
                <span id="custom-testing-active-project" className="text-xs font-mono font-semibold text-yellow-300">
                  {selectedProject?.name ?? realProjectId}
                </span>
              </div>

              <div>
                <label htmlFor="custom-testing-scope" className="block text-xs font-mono text-slate-400 mb-1">
                  Module / Scope <span className="text-slate-600">(user-provided — this project has no module metadata)</span>
                </label>
                <input
                  id="custom-testing-scope"
                  type="text"
                  value={scope}
                  onChange={(e) => setScope(e.target.value)}
                  placeholder="e.g. Authentication, Payments, User Management (optional)"
                  disabled={isAnalyzing}
                  className="w-full px-3 py-2 rounded-md bg-[#020617] border border-slate-700 text-sm font-mono text-slate-100 placeholder-slate-600 focus:outline-none focus:border-violet-500 disabled:opacity-60"
                />
              </div>

              <div>
                <label htmlFor="custom-testing-requirement" className="block text-xs font-mono text-slate-400 mb-1">
                  Custom Testing Requirement
                </label>
                <textarea
                  id="custom-testing-requirement"
                  value={requirementText}
                  onChange={(e) => setRequirementText(e.target.value)}
                  placeholder='e.g. "Test whether users can bypass role restrictions by changing API requests." or "Check login behavior after five invalid attempts."'
                  disabled={isAnalyzing}
                  rows={5}
                  className="w-full px-3 py-2 rounded-md bg-[#020617] border border-slate-700 text-sm font-mono text-slate-100 placeholder-slate-600 focus:outline-none focus:border-violet-500 disabled:opacity-60 resize-y"
                />
              </div>

              <div className="flex items-center justify-between pt-1">
                {getAnalysisStatusBadge(status)}
                <button
                  type="button"
                  id="btn-analyze-and-generate"
                  onClick={handleAnalyzeAndGenerate}
                  disabled={isAnalyzing}
                  className="flex items-center gap-1.5 px-5 py-2 rounded-md bg-violet-600 hover:bg-violet-500 text-white font-mono text-xs font-bold cursor-pointer transition-colors shadow-md disabled:opacity-60 disabled:cursor-not-allowed"
                >
                  <Sparkles className="w-4 h-4" />
                  <span>{isAnalyzing ? 'Analyzing…' : 'Analyze & Generate'}</span>
                </button>
              </div>

              {errorMessage && (status === 'VALIDATION_FAILED' || status === 'AI_UNAVAILABLE' || status === 'GENERATION_FAILED' || status === 'PROJECT_ACCESS_DENIED' || status === 'ANALYSIS_FAILED' || status === 'NO_GENERATED_TEST_CASES') && (
                <p id="custom-testing-error" className="text-xs font-mono text-rose-300/90">
                  {errorMessage}
                </p>
              )}
            </div>

            {analysis && (
              <div id="custom-testing-strategy" className="p-4 rounded-lg bg-[#0B1120] border border-slate-800 shadow-sm space-y-4">
                <div className="flex items-center gap-2 pb-2 border-b border-slate-800/80">
                  <ClipboardList className="w-4 h-4 text-violet-400" />
                  <span className="text-sm font-mono font-bold text-slate-200">Generated Strategy</span>
                </div>

                <StrategyField icon={Target} label="Objective" text={analysis.objective} />
                <StrategyField icon={Info} label="Normalized Scope" text={analysis.normalized_scope} />
                <StrategyListField icon={ListChecks} label="Recommended Testing Types" items={analysis.recommended_testing_types} />
                <StrategyListField icon={ShieldAlert} label="Risk Areas" items={analysis.risk_areas} />

                {analysis.recommended_skills.length > 0 && (
                  <div>
                    <div className="flex items-center gap-1.5 text-[11px] font-mono text-slate-400 mb-1.5">
                      <Sparkles className="w-3.5 h-3.5" />
                      <span>AI-Recommended Skills (distinct from your own selection below)</span>
                    </div>
                    <div className="flex flex-wrap gap-1.5">
                      {analysis.recommended_skills.map((name) => {
                        const alreadySelected = skills.some((s) => s.name.toLowerCase() === name.toLowerCase() && selectedSkillIds.includes(s.id));
                        return (
                          <button
                            key={name}
                            type="button"
                            onClick={() => handleAddRecommendedSkill(name)}
                            disabled={alreadySelected}
                            className={`px-2.5 py-1 rounded text-[11px] font-mono border transition-colors ${
                              alreadySelected
                                ? 'bg-emerald-950/60 border-emerald-700 text-emerald-300 cursor-default'
                                : 'bg-slate-900 border-slate-700 text-slate-300 hover:border-violet-500 hover:text-violet-300 cursor-pointer'
                            }`}
                          >
                            {alreadySelected ? `✓ ${name}` : `+ ${name}`}
                          </button>
                        );
                      })}
                    </div>
                  </div>
                )}

                <StrategyListField icon={Lightbulb} label="Assumptions" items={analysis.assumptions} />
                <StrategyListField icon={ListChecks} label="Prerequisites" items={analysis.prerequisites} />
                <StrategyListField icon={AlertTriangle} label="Limitations" items={analysis.limitations} tone="amber" />
                <StrategyField icon={Info} label="Generation Approach" text={analysis.generation_approach} />
              </div>
            )}

            {result && result.test_cases.length > 0 && (
              <div id="custom-testing-generated-cases" className="p-4 rounded-lg bg-[#0B1120] border border-slate-800 shadow-sm space-y-3">
                <div className="flex items-center justify-between pb-2 border-b border-slate-800/80">
                  <div className="flex items-center gap-2">
                    <CheckCircle2 className="w-4 h-4 text-emerald-400" />
                    <span className="text-sm font-mono font-bold text-slate-200">
                      Generated Test Cases ({result.test_cases.length})
                    </span>
                  </div>
                  <button
                    type="button"
                    id="btn-continue-to-test-case-generator"
                    onClick={handleContinueToTestCaseGenerator}
                    className="flex items-center gap-1.5 px-4 py-1.5 rounded-md bg-emerald-600 hover:bg-emerald-500 text-white font-mono text-xs font-bold cursor-pointer transition-colors shadow-md"
                  >
                    <span>Continue to Test Case Generator</span>
                    <ArrowRight className="w-3.5 h-3.5" />
                  </button>
                </div>
                <div className="space-y-2">
                  {result.test_cases.map((tc, i) => (
                    <div key={i} className="p-2.5 rounded bg-[#020617] border border-slate-800 flex items-center justify-between gap-3">
                      <div className="min-w-0">
                        <p className="text-xs font-mono text-slate-200 truncate">{tc.title}</p>
                        <p className="text-[10px] font-mono text-slate-500">
                          {tc.category} • {tc.priority} • {tc.severity} • {tc.evidence}
                        </p>
                      </div>
                    </div>
                  ))}
                </div>
                <p className="text-[10px] font-mono text-slate-500">
                  Review, save, validate, approve, and hand off to real execution on the Test Case Generator page — the exact same pipeline every other generated test case already uses.
                </p>
              </div>
            )}

            {status === 'NO_GENERATED_TEST_CASES' && analysis && (
              <p className="text-xs font-mono text-amber-300/90">
                No test cases to continue with — the real strategy above was produced, but no candidate case passed quality/traceability validation.
              </p>
            )}
          </div>

          <div className="lg:col-span-3 min-w-0">
            <SkillsAndMcpPanel
              skills={skills}
              selectedSkillIds={selectedSkillIds}
              onToggleSkill={toggleSkill}
              onAddCustomSkill={addCustomSkill}
              disabled={isAnalyzing}
            />
          </div>
        </div>
      )}
    </div>
  );
};

function getAnalysisStatusBadge(status: AnalysisStatus) {
  switch (status) {
    case 'ANALYZING':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-purple-950/80 border border-purple-700/80 text-purple-300">
          <Sparkles className="w-3.5 h-3.5 text-purple-400 animate-pulse" />
          Analyzing Requirement
        </span>
      );
    case 'GENERATED':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-emerald-950/80 border border-emerald-700/80 text-emerald-300">
          <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
          Generated
        </span>
      );
    case 'AI_UNAVAILABLE':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-rose-950/80 border border-rose-700/80 text-rose-300">
          <XCircle className="w-3.5 h-3.5 text-rose-400" />
          AI Unavailable
        </span>
      );
    case 'GENERATION_FAILED':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-rose-950/80 border border-rose-700/80 text-rose-300">
          <XCircle className="w-3.5 h-3.5 text-rose-400" />
          Generation Failed
        </span>
      );
    case 'NO_GENERATED_TEST_CASES':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-amber-950/80 border border-amber-700/80 text-amber-300">
          <AlertTriangle className="w-3.5 h-3.5 text-amber-400" />
          No Test Cases Produced
        </span>
      );
    case 'VALIDATION_FAILED':
    case 'PROJECT_ACCESS_DENIED':
    case 'ANALYSIS_FAILED':
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-bold bg-rose-950/80 border border-rose-700/80 text-rose-300">
          <XCircle className="w-3.5 h-3.5 text-rose-400" />
          {status === 'VALIDATION_FAILED' ? 'Validation Failed' : status === 'PROJECT_ACCESS_DENIED' ? 'Project Access Denied' : 'Analysis Failed'}
        </span>
      );
    case 'NO_ACTIVE_PROJECT':
    case 'IDLE':
    default:
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-mono font-semibold bg-slate-900 border border-slate-700 text-yellow-400">
          <span className="w-2 h-2 rounded-full bg-yellow-400 animate-pulse" />
          Ready
        </span>
      );
  }
}

const StrategyField: React.FC<{ icon: React.ComponentType<{ className?: string }>; label: string; text: string }> = ({ icon: Icon, label, text }) => (
  <div>
    <div className="flex items-center gap-1.5 text-[11px] font-mono text-slate-400 mb-1">
      <Icon className="w-3.5 h-3.5" />
      <span>{label}</span>
    </div>
    <p className="text-xs font-mono text-slate-200">{text}</p>
  </div>
);

const StrategyListField: React.FC<{ icon: React.ComponentType<{ className?: string }>; label: string; items: string[]; tone?: 'amber' }> = ({
  icon: Icon,
  label,
  items,
  tone,
}) => {
  if (items.length === 0) return null;
  return (
    <div>
      <div className="flex items-center gap-1.5 text-[11px] font-mono text-slate-400 mb-1">
        <Icon className="w-3.5 h-3.5" />
        <span>{label}</span>
      </div>
      <ul className={`list-disc list-inside text-xs font-mono space-y-0.5 ${tone === 'amber' ? 'text-amber-300/90' : 'text-slate-300'}`}>
        {items.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </div>
  );
};
