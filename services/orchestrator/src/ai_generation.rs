//! Phase 2 — AI-powered, skill-aware test case generation.
//!
//! Superseded provider/router internals (a later "AI Model Auto-Discovery,
//! Smart Routing & AI Settings" unit): this module used to own a single
//! hardcoded `OllamaProvider`/`AiModelRouter` pair directly. That has been
//! replaced by a call into the central `ai_router::AiInfrastructure` (task
//! `AiTask::TestCaseGeneration`) — this module keeps only what is genuinely
//! task-specific to test-case generation (skill resolution, prompt
//! building, the structured schema, validation/traceability/dedup).
//!
//! Architecture (brief §THIRD), per wave (see "Wave-based generation" below
//! for what selects which skills run in which wave, and why):
//! ```text
//! Generation Request
//!         v
//! Skill Resolver          (resolve_skill_instructions)
//!         v
//! Wave Partitioning        (partition_skills_into_waves — Base / Dependent /
//!                            NonFunctional, see "Wave-based generation")
//!         v
//! Feedback Context         (intelligence::Intelligence::load_feedback_context
//!                            — real risk/flakiness scores + human-CONFIRMED
//!                            defect patterns from this project's own past
//!                            execution history; empty/default for a project
//!                            with no history yet, never fabricated. See
//!                            "Self-learning loop" below.)
//!         v
//! Prompt Builder          (build_prompt — folds the requirement text, this
//!                            wave's skill instructions, the feedback context
//!                            above, AND any earlier wave's own real output
//!                            into one prompt — see build_prior_wave_block)
//!         v
//! Central AI Infrastructure (ai_router::AiInfrastructure::generate,
//!                             task = TEST_CASE_GENERATION — discovery,
//!                             capability matching, scoring, fallback all
//!                             live there now, shared by every AI task)
//!         v
//! Structured JSON Output   (serde-deserialized into GeneratedTestCaseDraft)
//!         v
//! Schema validation        (serde deserialization itself: a required
//!                            field's absence is a real parse failure)
//!         v
//! Quality validation        (validate_and_clean)
//!         v
//! Traceability validation   (enforce_traceability — a source_reference
//!                            that is not actually a substring of the real
//!                            requirement text is stripped, not trusted)
//!         v
//! Deduplication             (deduplicate — once per wave, then once more
//!                            across every wave's combined output)
//!         v
//! GenerationOutcome::Ai { .. } | GenerationOutcome::Failed { reason }
//! ```
//! `GenerationOutcome::Failed` is a real, first-class, non-panicking result
//! — the caller (`api.rs::generate_ai_test_cases_scoped`) reports it
//! honestly as `generation_method: "fallback"`, never as a silent success.
//!
//! **Wave-based generation (closes another gap this module's own
//! architecture left open — "single prompt, one AI call, every selected
//! skill combined with no inter-wave dependency"):** the caller-facing
//! `generate_test_cases` signature carried unchanged through this phase
//! (a later phase — "real crawler context" below — has since added one
//! more parameter to it), but it is no longer one call.
//! `partition_skills_into_waves` splits the caller's selection into three
//! real dependency phases, always attempted in this fixed order — Base
//! (skills that stand on the requirement text alone), Dependent (skills
//! that genuinely benefit from seeing Base's real output first — RBAC and
//! Business Case Testing: building a role/permission or business-rule
//! *variant* of a flow Base already covers is more grounded than inventing
//! one blind), and NonFunctional (Security/Performance, which sees both
//! Base's flows and Dependent's role output). A phase with nothing
//! selected for it is never attempted. See `wave_for_skill_name`'s own doc
//! comment for why each skill is assigned where it is, and `WaveSummary`
//! for how a partial failure is reported honestly rather than silently
//! reducing coverage with no signal.
//!
//! **Per-skill calls within a wave (closes the gap real usage surfaced:
//! bundling every selected skill in a phase into one shared prompt reliably
//! produced one small, shared-budget set of cases — e.g. ~10-15 total for a
//! typical multi-skill selection — never each skill's own full scenario
//! space):** within a phase, every selected skill now makes its own real,
//! separate generation call rather than sharing one combined call with the
//! phase's other skills. Each call still sees every real case generated by
//! every earlier call so far, in order — same `build_prior_wave_block`
//! mechanism as before, now threaded at per-skill rather than per-phase
//! granularity, so a later skill (even one in the same phase) still avoids
//! repeating an earlier skill's exact scenario, with `deduplicate` as the
//! real safety net for anything that still slips through. The one
//! exception, preserved exactly: an entirely empty skill selection across
//! all three phases still makes the one call it always has, with no skill
//! named — behavior no existing zero-skill caller depends on changes. This
//! also means `WaveSummary` (below) now describes one skill's own call, not
//! a whole phase's combined one — `waves.len()` is the real number of
//! calls actually made, not a fixed 3.
//!
//! **Self-learning loop (closes a gap this module's own architecture left
//! open):** `intelligence.rs::ingest_run` has, since an earlier phase,
//! computed real risk/flakiness scores and clustered/confirmed real defect
//! patterns after every run — but nothing read any of it back into
//! generation. `FeedbackContext`/`build_feedback_context` below is that read
//! path: the caller (`api.rs`) loads it once per generation call via
//! `intelligence::Intelligence::load_feedback_context` and threads it
//! through `generate_test_cases` into the prompt. It is deliberately
//! additive, not a new evidence path — see `build_feedback_block`'s own doc
//! comment for why a test case it inspires still answers to the EVIDENCE
//! RULES above, exactly like every other test case.
//!
//! **Real crawler context (closes the gap `crawler.rs`'s own module doc
//! comment left explicit — Phase 6 built a real crawler + per-role
//! visibility matrix with no consumer wired up):** `generate_test_cases`
//! now takes one more parameter, `crawl: Option<&crawler::CrawlOutput>` —
//! the real, structured result of a completed crawl run
//! (`GET .../crawl/:run_id/result`'s own data), threaded through every wave
//! into `build_prompt` via `build_crawl_context_block`. `None` (no crawl
//! selected, or the caller never ran one) renders nothing and changes
//! nothing — every existing single-document-only caller behaves exactly as
//! before. When present, two real signals ground generation in the actual
//! running application rather than only a written requirement: the real
//! pages/elements a browser actually reached, and the crawl's own real
//! per-URL role-visibility differences (a genuine, observed access-control
//! boundary a Security/RBAC-Testing case can be grounded in, not an
//! invented one). Still governed by the same EVIDENCE RULES as everything
//! else in the prompt — a case this inspires is not automatically
//! "evidenced" just because a real element existed; the requirement text is
//! still what decides evidenced vs. inferred vs. exploratory.

