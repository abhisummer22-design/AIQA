/// Extracts the JSON payload from a model response that may legally carry
/// conversational noise around it. Real OpenAI-compatible chat models
/// (including the MJ gateway's qwen3, observed live) sometimes wrap the
/// requested JSON object in markdown fences, precede it with reasoning
/// prose or `<think>` blocks, or append trailing commentary — none of
/// which change the JSON itself. Strategy: strip `<think>` blocks and
/// code fences first; if the remainder still isn't parseable at the
/// top level, fall back to the outermost `{...}` span. Returns `None`
/// when no plausible JSON object exists at all.
pub(crate) fn extract_json_payload(text: &str) -> Option<String> {
    let mut working = text.trim().to_string();

    // Strip one or more <think>...</think> blocks (qwen-style reasoning
    // models emit these inside `content` when thinking is enabled).
    while let Some(start) = working.find("<think>") {
        match working[start..].find("</think>") {
            Some(end_off) => working.replace_range(start..start + end_off + "</think>".len(), ""),
            None => {
                // Unterminated think block: everything from <think> on is reasoning.
                working.truncate(start);
                break;
            }
        }
    }
    let working = working.trim();

    // Strip markdown code fences: ```json ... ``` or ``` ... ```
    if working.starts_with("```") {
        let inner = working.trim_start_matches('`');
        let inner = inner
            .strip_prefix("json")
            .map(str::trim_start)
            .unwrap_or(inner);
        let end = inner.rfind("```").unwrap_or(inner.len());
        return Some(inner[..end].trim().to_string());
    }

    // Fast path: already a bare JSON object.
    if working.starts_with('{') && working.ends_with('}') {
        return Some(working.to_string());
    }

    // Fallback: outermost brace span (prose before/after the object).
    let start = working.find('{')?;
    let end = working.rfind('}')?;
    if end > start {
        Some(working[start..=end].to_string())
    } else {
        None
    }
}

/// One real generation call for one wave's selected skills — the exact
/// pipeline (brief §THIRD) `generate_test_cases` used to run once, total,
/// for every selected skill combined. Now it is the building block
/// `generate_test_cases` below calls up to three times, once per non-empty
/// wave: resolve this wave's skills, build the prompt (folding in the
/// feedback context and, for a Dependent/NonFunctional wave, every earlier
/// wave's real output via `prior_wave_cases`), route+execute through
/// `infra`, then validate/traceability-check/deduplicate whatever came back
/// — or return a real, honest failure. Never returns a fabricated success.
/// This is the boundary crossing the later "Central AI Model Auto-Discovery,
/// Smart Routing & AI Settings" unit's own §17 describes ("Test Case
/// Generator does not need to know whether the model is Ollama/Gemini/
/// OpenAI/another provider") — crossed through the shared router, not a
/// private provider of its own, once per wave.
async fn generate_one_wave(
    infra: &AiInfrastructure,
    requirement_text: &str,
    skills: &[SkillInput],
    feedback: &FeedbackContext,
    prior_wave_cases: &[GeneratedTestCaseDraft],
    crawl: Option<&crate::crawler::CrawlOutput>,
) -> GenerationOutcome {
    let resolved = resolve_skill_instructions_for(infra, skills).await;
    let prompt = build_prompt(
        requirement_text,
        &resolved,
        feedback,
        prior_wave_cases,
        crawl,
    );

    let request = AiRequest {
        task: AiTask::TestCaseGeneration,
        prompt,
        preferred_provider: None,
        preferred_model: None,
    };

    // One retry on a degenerate response: real models occasionally return
    // an empty object (`{}` observed live from ollama's json-format mode)
    // or prose-only output while being substantively capable — a second,
    // identical call is genuine nondeterminism recovery, not a fabricated
    // success (every attempt is still fully validated below).
    let mut last_failure: Option<String> = None;
    for _attempt in 0..2 {
        let result = match infra.generate(request.clone()).await {
            GenerationOutcome2::Ok(r) => r,
            GenerationOutcome2::Failed { reason } => return GenerationOutcome::Failed { reason },
        };

        let outcome = validate_structured_output(&result, requirement_text);
        match outcome {
            Ok(cases) => return cases,
            Err(reason) => last_failure = Some(reason),
        }
    }
    GenerationOutcome::Failed {
        reason: last_failure.unwrap_or_else(|| "unknown generation failure".to_string()),
    }
}

/// One wave's real, honest outcome — the concrete mechanism by which a
/// partial-wave failure (e.g. the Dependent wave times out while Base
/// succeeded) stays visible rather than silently reducing coverage with no
/// signal, the same "never a silent success/never a silently dropped
/// failure" standard this module already holds `GenerationOutcome` itself
/// to. `skipped: true` (rather than a variant/`Option`) makes "this wave had
/// nothing selected, so it was never attempted at all" and "this wave was
/// attempted and failed" (`skipped: false`, `failure_reason: Some(..)`) two
/// genuinely distinct, both-honest states — collapsing them would make a
/// deliberate no-op look like a failure.
#[derive(Debug, Clone, Serialize)]
pub struct WaveSummary {
    pub wave: &'static str,
    pub skill_names: Vec<String>,
    pub case_count: usize,
    pub provider: Option<String>,
    pub model: Option<String>,
    pub routing_score: Option<f64>,
    pub fallback_used: Option<bool>,
    pub routing_mode: Option<String>,
    /// This wave's own real token counts / cost — `None` for a
    /// skipped/failed wave (it made no real call), and also honestly
    /// `None` on a successful wave whose provider genuinely reported no
    /// usage figure (`ai_router::TokenUsage`'s own contract).
    pub prompt_tokens: Option<u32>,
    pub completion_tokens: Option<u32>,
    pub estimated_cost_usd: Option<f64>,
    /// Real, measured wall-clock time for this wave's one call — `None`
    /// only when the wave never made a call at all (skipped); always
    /// `Some` for a wave that was attempted, success or failure alike, so
    /// consider extending this to failed waves too before relying on it
    /// there (`run_wave`'s failure arm currently leaves it `None`, matching
    /// `provider`/`model`'s own precedent of describing a *successful*
    /// call only).
    pub latency_ms: Option<u64>,
    pub failure_reason: Option<String>,
    pub skipped: bool,
    /// Requirement-driven generation only: which batch of this skill's
    /// requirements the call carried (`"2/5"`) and how many requirements
    /// were in it. Absent otherwise.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub batch: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub requirements: Option<usize>,
    /// Coverage top-up calls only: the technique the call was asked for.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub technique: Option<String>,
}

impl WaveSummary {
    /// Test-fixture convenience only: production code no longer creates an
    /// explicit "this wave was skipped" placeholder (the per-skill
    /// `generate_test_cases` orchestration above simply never calls
    /// `run_wave` for a phase nothing was selected for, rather than pushing
    /// one of these into `waves`) — `skipped` itself stays a real field on
    /// a genuine `WaveSummary`, only this specific always-`skipped: true`
    /// constructor is test-only now.
    #[cfg(test)]
    fn skipped(wave: Wave) -> Self {
        Self {
            wave: wave.label(),
            skill_names: Vec::new(),
            case_count: 0,
            provider: None,
            model: None,
            routing_score: None,
            fallback_used: None,
            routing_mode: None,
            prompt_tokens: None,
            completion_tokens: None,
            estimated_cost_usd: None,
            latency_ms: None,
            failure_reason: None,
            skipped: true,
            batch: None,
            requirements: None,
            technique: None,
        }
    }

    pub(crate) fn succeeded(&self) -> bool {
        !self.skipped && self.failure_reason.is_none()
    }
}

/// Real, summed usage across every wave that actually ran and produced
/// output (mirrors `crawl_pages_used_count`'s role for crawl grounding — a
/// small, independently testable rollup the API layer calls rather than
/// re-deriving). A skipped or failed wave made no real call and
/// contributes nothing. `prompt_tokens`/`completion_tokens`/
/// `estimated_cost_usd` are `None` the moment even one wave that DID run
/// has an honestly-unknown figure of its own — a partial sum would silently
/// understate real usage, which is worse than admitting the total isn't
/// fully knowable.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct WaveUsageTotals {
    pub prompt_tokens: Option<u32>,
    pub completion_tokens: Option<u32>,
    pub estimated_cost_usd: Option<f64>,
    pub latency_ms: u64,
}

pub fn aggregate_wave_usage(waves: &[WaveSummary]) -> WaveUsageTotals {
    let ran: Vec<&WaveSummary> = waves.iter().filter(|w| w.succeeded()).collect();

    let mut prompt_tokens = Some(0u32);
    let mut completion_tokens = Some(0u32);
    let mut estimated_cost_usd = Some(0.0f64);
    let mut latency_ms = 0u64;

    for w in &ran {
        prompt_tokens = prompt_tokens.zip(w.prompt_tokens).map(|(a, b)| a + b);
        completion_tokens = completion_tokens
            .zip(w.completion_tokens)
            .map(|(a, b)| a + b);
        estimated_cost_usd = estimated_cost_usd
            .zip(w.estimated_cost_usd)
            .map(|(a, b)| a + b);
        latency_ms += w.latency_ms.unwrap_or(0);
    }

    if ran.is_empty() {
        prompt_tokens = None;
        completion_tokens = None;
        estimated_cost_usd = None;
    }

    WaveUsageTotals {
        prompt_tokens,
        completion_tokens,
        estimated_cost_usd,
        latency_ms,
    }
}

/// Runs exactly one wave via `generate_one_wave` and turns its real outcome
/// into a `WaveSummary` plus whatever cases it actually produced (empty on
/// failure) — the one place the `GenerationOutcome::Ai { .. }` match needed
/// to tolerate `generate_one_wave`'s own (always-empty) `waves` field, kept
/// here so `generate_test_cases` below does not repeat this three times.
async fn run_wave(
    infra: &AiInfrastructure,
    requirement_text: &str,
    wave: Wave,
    skills: &[SkillInput],
    feedback: &FeedbackContext,
    prior_wave_cases: &[GeneratedTestCaseDraft],
    crawl: Option<&crate::crawler::CrawlOutput>,
    progress: Option<(&LogBus, &str)>,
) -> (WaveSummary, Vec<GeneratedTestCaseDraft>) {
    let skill_names: Vec<String> = skills.iter().map(|s| s.name.clone()).collect();

    // Real, in-flight signal for a caller that wants to know which wave is
    // running *right now* (the Test Case Generator's live skill indicator),
    // not only the after-the-fact `WaveSummary` every caller already gets
    // once the whole multi-wave request finishes. Emitted on the same
    // `log_bus`/source a wave's later "generated N case(s)"/"failed" lines
    // already use, distinguished only by ending in "started" — no new
    // message schema, just the one additional real moment reported.
    // `None` (unit tests; `custom_testing.rs`'s synchronous batch path)
    // changes nothing else about this function's behavior.
    if let Some((log_bus, project_id)) = progress {
        log_bus
            .emit(
                "INFO",
                "generation",
                &format!(
                    "Wave '{}' ({}) started",
                    wave.label(),
                    skill_names.join(", ")
                ),
                None,
                Some(project_id),
                None,
            )
            .await;
    }

    match generate_one_wave(
        infra,
        requirement_text,
        skills,
        feedback,
        prior_wave_cases,
        crawl,
    )
    .await
    {
        GenerationOutcome::Ai {
            cases,
            provider,
            model,
            routing_score,
            fallback_used,
            routing_mode,
            prompt_tokens,
            completion_tokens,
            latency_ms,
            estimated_cost_usd,
            ..
        } => {
            let summary = WaveSummary {
                wave: wave.label(),
                skill_names,
                case_count: cases.len(),
                provider: Some(provider),
                model: Some(model),
                routing_score: Some(routing_score),
                fallback_used: Some(fallback_used),
                routing_mode: Some(routing_mode),
                prompt_tokens,
                completion_tokens,
                estimated_cost_usd,
                latency_ms: Some(latency_ms),
                failure_reason: None,
                skipped: false,
                batch: None,
                requirements: None,
                technique: None,
            };
            (summary, cases)
        }
        GenerationOutcome::Failed { reason } => {
            let summary = WaveSummary {
                wave: wave.label(),
                skill_names,
                case_count: 0,
                provider: None,
                model: None,
                routing_score: None,
                fallback_used: None,
                routing_mode: None,
                prompt_tokens: None,
                completion_tokens: None,
                estimated_cost_usd: None,
                latency_ms: None,
                failure_reason: Some(reason),
                skipped: false,
                batch: None,
                requirements: None,
                technique: None,
            };
            (summary, Vec::new())
        }
    }
}

/// The real, single entry point (brief §THIRD). `crawl` is the one
/// parameter added since wave-based generation shipped — `None` for every
/// caller that has no completed crawl to ground against (`custom_testing.rs`
/// always passes `None`; every existing single-wave-selection test does
/// too) reduces to the exact behaviour every existing caller already had.
/// Internally: `partition_skills_into_waves` splits the selection into its
/// three dependency phases, then one real, separate `generate_one_wave` call
/// (via `run_wave`) runs per selected skill, phase by phase in that fixed
/// order, each call seeing every earlier call's real output. The one
/// exception is an entirely empty selection, which reduces to exactly the
/// one call today's zero-skill callers already expect. Cases from every
/// call that produced real output are combined and deduplicated once more
/// across the full set (a later call can still coincidentally repeat an
/// earlier one's exact scenario despite being told not to). The final
/// outcome is `Ai` if *any* call produced real cases — a working Base call
/// must not be discarded just because another selected skill's call failed
/// — and `Failed` only when every attempted call failed. `waves` carries
/// the real, per-call breakdown either way (its length is the real number
/// of calls made, not a fixed 3); see `WaveSummary`. Top-level `provider`/
/// `model`/`routing_score`/`fallback_used`/`routing_mode` describe the LAST
/// call that succeeded (existing callers that only read those top-level
/// fields see real, meaningful values either way — for a single-skill
/// selection, the only call that ran).
pub async fn generate_test_cases(
    infra: &AiInfrastructure,
    requirement_text: &str,
    skills: &[SkillInput],
    feedback: &FeedbackContext,
    crawl: Option<&crate::crawler::CrawlOutput>,
    progress: Option<(&LogBus, &str)>,
) -> GenerationOutcome {
    let (base, dependent, non_functional) = partition_skills_into_waves(skills);

    let mut all_cases: Vec<GeneratedTestCaseDraft> = Vec::new();
    let mut waves: Vec<WaveSummary> = Vec::new();

    // An entirely empty selection across all three phases still makes
    // exactly the one call it always has, with no skill named — the one
    // real exception to "one call per selected skill" below, preserved so
    // no existing zero-skill caller's behavior changes.
    if base.is_empty() && dependent.is_empty() && non_functional.is_empty() {
        let (summary, cases) = run_wave(
            infra,
            requirement_text,
            Wave::Base,
            &base,
            feedback,
            &[],
            crawl,
            progress,
        )
        .await;
        waves.push(summary);
        all_cases.extend(cases);
    } else {
        // One real, separate call per selected skill, phase by phase in
        // the fixed Base -> Dependent -> NonFunctional order — never
        // combining several skills' instructions into one shared call
        // (see the module doc comment's "Per-skill calls within a wave").
        // Every call, in every phase, sees every real case every earlier
        // call has produced so far: a later Base skill still avoids
        // repeating an earlier Base skill's exact scenario, and Dependent/
        // NonFunctional skills still see the full real Base (+ Dependent)
        // output the architecture already called for.
        for skill in &base {
            let (summary, cases) = run_wave(
                infra,
                requirement_text,
                Wave::Base,
                std::slice::from_ref(skill),
                feedback,
                &all_cases,
                crawl,
                progress,
            )
            .await;
            waves.push(summary);
            all_cases.extend(cases);
        }
        for skill in &dependent {
            let (summary, cases) = run_wave(
                infra,
                requirement_text,
                Wave::Dependent,
                std::slice::from_ref(skill),
                feedback,
                &all_cases,
                crawl,
                progress,
            )
            .await;
            waves.push(summary);
            all_cases.extend(cases);
        }
        for skill in &non_functional {
            let (summary, cases) = run_wave(
                infra,
                requirement_text,
                Wave::NonFunctional,
                std::slice::from_ref(skill),
                feedback,
                &all_cases,
                crawl,
                progress,
            )
            .await;
            waves.push(summary);
            all_cases.extend(cases);
        }
    }

    finish_waves(waves, all_cases, deduplicate)
}

/// Turns the calls a generation made into its outcome: `Ai` when any call
/// produced real cases (its top-level fields describe the LAST call that
/// did), `Failed` — each distinct reason once — when every call failed.
/// `dedupe` is the final, whole-run de-duplication of the merged cases.
pub(crate) fn finish_waves(
    waves: Vec<WaveSummary>,
    all_cases: Vec<GeneratedTestCaseDraft>,
    dedupe: fn(Vec<GeneratedTestCaseDraft>) -> Vec<GeneratedTestCaseDraft>,
) -> GenerationOutcome {
    let Some(last_success) = waves.iter().rev().find(|w| w.succeeded()) else {
        // Every skill call usually fails for the same reason (one provider is down or refusing), so say each
        // distinct reason once instead of once per skill.
        let mut reasons: Vec<&str> = Vec::new();
        for reason in waves.iter().filter_map(|w| w.failure_reason.as_deref()) {
            if !reasons.contains(&reason) {
                reasons.push(reason);
            }
        }
        let reason = reasons.join("; ");
        return GenerationOutcome::Failed {
            reason: if reason.is_empty() {
                "no wave produced any output".to_string()
            } else {
                reason
            },
        };
    };
    let provider = last_success
        .provider
        .clone()
        .expect("a succeeded wave always has a provider");
    let model = last_success
        .model
        .clone()
        .expect("a succeeded wave always has a model");
    let routing_score = last_success
        .routing_score
        .expect("a succeeded wave always has a routing_score");
    let fallback_used = last_success
        .fallback_used
        .expect("a succeeded wave always has fallback_used");
    let routing_mode = last_success
        .routing_mode
        .clone()
        .expect("a succeeded wave always has a routing_mode");
    let latency_ms = last_success
        .latency_ms
        .expect("a succeeded wave always has a measured latency");
    // Real, but honestly optional even on success (the provider itself may
    // not have reported usage) — passed through as-is, never `.expect()`ed.
    let prompt_tokens = last_success.prompt_tokens;
    let completion_tokens = last_success.completion_tokens;
    let estimated_cost_usd = last_success.estimated_cost_usd;

    // Cross-wave dedup: a later wave can still coincidentally repeat an
    // earlier wave's exact scenario despite `build_prior_wave_block` asking
    // it not to — this is the same real, rule-based `deduplicate` every
    // single wave's own `validate_structured_output` already applies,
    // applied once more across the full merged set.
    let deduped = dedupe(all_cases);

    GenerationOutcome::Ai {
        cases: deduped,
        provider,
        model,
        routing_score,
        fallback_used,
        routing_mode,
        prompt_tokens,
        completion_tokens,
        latency_ms,
        estimated_cost_usd,
        waves,
    }
}

/// Parses + validates one raw model response into final deduplicated test
/// cases, or a real failure reason.
fn validate_structured_output(
    result: &crate::ai_router::GenerationResult,
    requirement_text: &str,
) -> Result<GenerationOutcome, String> {
    let cleaned = parse_and_clean(result)?;
    let traced = enforce_traceability(cleaned, requirement_text);
    // Before dedup, so a run of echoed titles is not first collapsed into one
    // bogus "case" that then survives as if it were real coverage.
    let unechoed = reject_echoed_titles(traced, requirement_text);
    let deduped = deduplicate(unechoed);

    if deduped.is_empty() {
        return Err(
            "AI response contained no usable test cases — every draft was either structurally invalid \
             or a verbatim copy of the requirement text"
                .to_string(),
        );
    }

    Ok(GenerationOutcome::Ai {
        cases: deduped,
        provider: result.provider.clone(),
        model: result.model.clone(),
        routing_score: result.routing_score,
        fallback_used: result.fallback_used,
        routing_mode: routing_mode_label(result),
        prompt_tokens: result.prompt_tokens,
        completion_tokens: result.completion_tokens,
        latency_ms: result.latency_ms,
        estimated_cost_usd: result.estimated_cost_usd,
        // A single wave call has no sub-waves of its own to report —
        // `generate_test_cases` is the only place that ever populates this.
        waves: Vec::new(),
    })
}

/// `"AUTO"` / `"MANUAL"`: the routing mode a result was produced under.
pub(crate) fn routing_mode_label(result: &crate::ai_router::GenerationResult) -> String {
    match result.routing_mode {
        crate::ai_router::RoutingMode::Manual => "MANUAL".to_string(),
        crate::ai_router::RoutingMode::Auto => "AUTO".to_string(),
    }
}

/// The JSON out of a raw model response, parsed into drafts and stripped of
/// the structurally unusable ones (a real failure reason when nothing usable
/// is left). What every generation path does before it checks the cases
/// against the text they were generated from.
pub(crate) fn parse_and_clean(
    result: &crate::ai_router::GenerationResult,
) -> Result<Vec<GeneratedTestCaseDraft>, String> {
    let payload = match extract_json_payload(&result.text) {
        Some(p) => p,
        None => {
            return Err(
                "invalid structured output: no JSON object found in AI response".to_string(),
            )
        }
    };
    let parsed: AiGenerationResponse = match serde_json::from_str(&payload) {
        Ok(v) => v,
        Err(e) => {
            // Real diagnostic, not a guess: which provider/model produced
            // the unusable shape, and the first bytes of what it said.
            let head: String = payload.chars().take(300).collect();
            tracing::warn!(
                "generate_test_cases: unparseable structured output from {}/{} ({} chars): {e}; payload head: {head}",
                result.provider,
                result.model,
                payload.len()
            );
            return Err(format!("invalid structured output: {e}"));
        }
    };

    let cleaned = validate_and_clean(parsed.test_cases);
    if cleaned.is_empty() {
        return Err("AI response contained no structurally valid test cases".to_string());
    }
    Ok(cleaned)
}

