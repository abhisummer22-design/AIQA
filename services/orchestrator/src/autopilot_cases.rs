//! What an autopilot run does with the test cases the AI writes, as far as it can be worked out without the network: how the
//! requirements are divided into groups to generate for, and how a generated draft becomes the request that saves it as a
//! test case.
//!
//! The mapping is the one the Test Case Generator page makes (`generatedCaseToCreateRequest` and `aiDraftToDisplay` in
//! `TestCaseGeneratorPage.tsx`), so a case an autopilot run saved reads in the Test Cases page like one a person saved from
//! the generator, with tags that say where it came from.

use crate::ai_generation::GeneratedTestCaseDraft;
use crate::autopilot::AutopilotConfig;
use serde_json::{json, Value};
use uuid::Uuid;

/// How many requirements are generated for in one request. A run generates in groups so that the cases of every group
/// that is done are kept, and a service that is stopped and started again does not begin again from the first requirement.
pub const CHUNK_REQUIREMENTS: usize = 10;

/// The requirement ids in the order they were given, each once, in groups of at most `size`.
pub fn chunks(keys: &[String], size: usize) -> Vec<Vec<String>> {
    let mut seen = std::collections::HashSet::new();
    let unique: Vec<String> = keys
        .iter()
        .filter(|key| seen.insert(key.as_str()))
        .cloned()
        .collect();
    unique.chunks(size.max(1)).map(<[String]>::to_vec).collect()
}

/// The request's own text, which every prompt of the run shows before the numbered requirements.
pub fn settings_text(config: &AutopilotConfig) -> String {
    let roles: Vec<&str> = config.roles.iter().map(|r| r.name.as_str()).collect();
    let mut text = format!(
        "Application under test: {}. Roles: {}.",
        config.base_url,
        roles.join(", ")
    );
    if let Some(depth) = config.depth.as_deref().filter(|d| !d.trim().is_empty()) {
        text.push_str(&format!(" Requested generation depth: {depth}."));
    }
    text
}

/// The tag every case of a run carries, to find them by.
pub fn run_tag(run: Uuid) -> String {
    format!("autopilot:{run}")
}

/// A tag naming one case of one group of a run (`ap:<start of the run's id>:<group>:<case>`), so that a case saved by an
/// attempt that a restart cut short is known when the group is saved again, and is not saved twice.
pub fn marker(run: Uuid, group: usize, case: usize) -> String {
    let id = run.to_string();
    format!("ap:{}:{group}:{case}", &id[..8])
}

/// What a case's request is worked out from besides the draft.
pub struct CaseInfo<'a> {
    pub run: Uuid,
    pub marker: String,
    /// The name of the skill that wrote the case, when it is one the run was given.
    pub skill_name: Option<&'a str>,
    /// The requirement the draft says it tests, as far as it is known: its id, its text and the document it is from.
    pub requirement_text: Option<&'a str>,
    pub document: Option<&'a str>,
    pub suite: Option<Uuid>,
    /// Who wrote it, for the case's own record of where it came from.
    pub provider: Option<&'a str>,
    pub model: Option<&'a str>,
}

fn category_tag(category: &str) -> String {
    category
        .to_lowercase()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join("-")
}

fn evidence_word(draft: &GeneratedTestCaseDraft) -> &'static str {
    match draft.evidence {
        crate::ai_generation::EvidenceKind::Evidenced => "evidenced",
        crate::ai_generation::EvidenceKind::Inferred => "inferred",
        crate::ai_generation::EvidenceKind::Exploratory => "exploratory",
    }
}

/// The body of `POST .../test-cases` for a generated draft.
pub fn case_request(draft: &GeneratedTestCaseDraft, info: &CaseInfo) -> Value {
    let skill = info.skill_name.unwrap_or(&draft.skill_id);
    let evidence = evidence_word(draft);
    let mut test_data = json!({
        "skill_id": draft.skill_id,
        "evidence": evidence,
        "source_reference": draft.source_reference,
    });
    if let Some(requirement) = &draft.requirement_id {
        test_data["requirement_id"] = json!(requirement);
    }
    if let Some(technique) = &draft.technique {
        test_data["technique"] = json!(technique);
    }
    let analysis = format!(
        "Generated by {}/{} in autopilot run {}{} — evidence: {evidence}{}{}{}.",
        info.provider.unwrap_or("an AI provider"),
        info.model.unwrap_or("an unreported model"),
        info.run,
        if info.skill_name.is_some() {
            format!(" (skill: {skill})")
        } else {
            String::new()
        },
        draft
            .requirement_id
            .as_ref()
            .map(|r| format!(", requirement: {r}"))
            .unwrap_or_default(),
        draft
            .technique
            .as_ref()
            .map(|t| format!(", technique: {t}"))
            .unwrap_or_default(),
        draft
            .source_reference
            .as_ref()
            .map(|s| format!(", cites: \"{s}\""))
            .unwrap_or_default(),
    );
    let reference = draft
        .requirement_id
        .clone()
        .or_else(|| draft.source_reference.clone());
    let mut tags = vec![
        category_tag(&draft.category),
        draft.skill_id.clone(),
        evidence.to_string(),
        "ai-generated".to_string(),
    ];
    if let Some(technique) = &draft.technique {
        tags.push(format!("technique:{technique}"));
    }
    tags.push(run_tag(info.run));
    tags.push(info.marker.clone());

    let mut request = json!({
        "title": draft.title,
        "description": format!(
            "AI-generated {} test case (skill: {skill}, evidence: {evidence}).",
            draft.category
        ),
        "category": draft.category,
        "priority": draft.priority,
        "severity": draft.severity,
        "preconditions": draft.preconditions,
        "steps": draft.steps.iter().enumerate().map(|(i, s)| json!({
            "step_number": i + 1,
            "action": s.action,
            "expected_result": s.expected_result,
        })).collect::<Vec<_>>(),
        "expected_result": draft.expected_result,
        "assertions": [draft.expected_result],
        "test_data": serde_json::to_string_pretty(&test_data).unwrap_or_default(),
        "requirement_reference": reference,
        "traceability": {
            "sourceDoc": info.document.unwrap_or("Autopilot run (documents chosen when it was made)"),
            "requirementRef": match (&draft.requirement_id, &draft.source_reference) {
                (Some(id), Some(quote)) => format!("{id} — cites: \"{quote}\""),
                (Some(id), None) => id.clone(),
                (None, Some(quote)) => quote.clone(),
                (None, None) => format!("Not cited ({evidence})"),
            },
            "requirementText": info.requirement_text.unwrap_or(""),
            "aiAnalysis": analysis,
            "testCaseId": info.marker,
            "testCategory": draft.category,
            "executionTarget": "Not yet assigned — assigned when the autopilot run executes it",
            "evidencePolicy": "Not yet captured — captured when the case is executed",
            "reportMapping": "Not yet mapped",
        },
        "risk_factor": match draft.priority.as_str() {
            "CRITICAL" => "HIGH",
            "HIGH" => "MEDIUM",
            _ => "LOW",
        },
        "tags": tags,
    });
    if let Some(document) = info.document {
        request["source_document"] = json!(document);
    }
    if let Some(text) = info.requirement_text {
        request["source_requirement"] = json!(text);
    }
    if let Some(suite) = info.suite {
        request["suite_id"] = json!(suite);
    }
    request
}

#[cfg(test)]
mod tests {
    use super::*;

    fn draft(extra: Value) -> GeneratedTestCaseDraft {
        let mut base = json!({
            "title": "Reject a short password",
            "category": "Security Testing",
            "skill_id": "skill-security-testing",
            "preconditions": ["A registered user"],
            "steps": [
                {"action": "Submit a 7-character password", "expected_result": "A validation error is shown"},
                {"action": "Submit an 8-character password", "expected_result": "The password is accepted"}
            ],
            "expected_result": "Only passwords of 8 characters or more are accepted",
            "priority": "HIGH",
            "severity": "MAJOR",
            "evidence": "evidenced",
            "source_reference": "at least 8 characters long",
            "requirement_id": "FRD-2-01",
            "technique": "negative"
        });
        for (key, value) in extra.as_object().cloned().unwrap_or_default() {
            base[key] = value;
        }
        serde_json::from_value(base).unwrap()
    }

    fn info<'a>() -> CaseInfo<'a> {
        CaseInfo {
            run: Uuid::parse_str("6f95ee30-3fc8-4bc6-9d6d-f8cb4c8ef988").unwrap(),
            marker: "ap:6f95ee30:2:3".to_string(),
            skill_name: Some("Security Testing"),
            requirement_text: Some("A password must be at least 8 characters long."),
            document: Some("FRD.md"),
            suite: None,
            provider: Some("ollama"),
            model: Some("qwen2.5:14b"),
        }
    }

    fn keys(list: &[&str]) -> Vec<String> {
        list.iter().map(|k| k.to_string()).collect()
    }

    #[test]
    fn requirements_are_divided_in_order_into_groups_of_the_size_and_a_short_last_one() {
        let all: Vec<String> = (1..=23).map(|n| format!("FR-{n:03}")).collect();
        let groups = chunks(&all, 10);
        assert_eq!(groups.len(), 3);
        assert_eq!(groups[0].len(), 10);
        assert_eq!(groups[1].len(), 10);
        assert_eq!(groups[2], keys(&["FR-021", "FR-022", "FR-023"]));
        assert_eq!(groups[0][0], "FR-001", "the order the requirements have");
        assert_eq!(groups[1][0], "FR-011");
        assert_eq!(
            chunks(&all[..10], 10).len(),
            1,
            "exactly one group's worth is one group"
        );
        assert_eq!(chunks(&all[..11], 10).len(), 2);
        assert!(
            chunks(&[], 10).is_empty(),
            "nothing to generate for is no group"
        );
        assert_eq!(CHUNK_REQUIREMENTS, 10);
    }

    #[test]
    fn an_id_two_documents_share_is_generated_for_once_and_a_size_of_nothing_is_one_at_a_time() {
        let shared = keys(&["FR-1", "FR-2", "FR-1", "FR-3", "FR-2"]);
        assert_eq!(chunks(&shared, 10), [keys(&["FR-1", "FR-2", "FR-3"])]);
        assert_eq!(
            chunks(&shared, 0).len(),
            3,
            "a group size of 0 does not divide by nothing"
        );
    }

    #[test]
    fn the_settings_text_names_the_application_the_roles_and_the_depth() {
        let config: AutopilotConfig = serde_json::from_value(json!({
            "base_url": "https://shop.example.test",
            "roles": [{"name": "anonymous"}, {"name": "admin"}],
            "depth": "STANDARD",
        }))
        .unwrap();
        assert_eq!(
            settings_text(&config),
            "Application under test: https://shop.example.test. Roles: anonymous, admin. Requested generation depth: STANDARD."
        );
        let plain: AutopilotConfig = serde_json::from_value(json!({
            "base_url": "https://shop.example.test", "roles": [{"name": "anonymous"}], "depth": "  ",
        }))
        .unwrap();
        assert_eq!(
            settings_text(&plain),
            "Application under test: https://shop.example.test. Roles: anonymous."
        );
    }

    #[test]
    fn a_run_has_a_tag_and_each_of_its_cases_a_marker_that_names_its_place() {
        let run = Uuid::parse_str("6f95ee30-3fc8-4bc6-9d6d-f8cb4c8ef988").unwrap();
        assert_eq!(
            run_tag(run),
            "autopilot:6f95ee30-3fc8-4bc6-9d6d-f8cb4c8ef988"
        );
        assert_eq!(marker(run, 2, 3), "ap:6f95ee30:2:3");
        assert_ne!(
            marker(run, 2, 3),
            marker(run, 3, 2),
            "group and case are not interchangeable"
        );
    }

    #[test]
    fn a_draft_becomes_the_request_the_generator_page_would_have_made() {
        let request = case_request(&draft(json!({})), &info());
        assert_eq!(request["title"], "Reject a short password");
        assert_eq!(
            request["description"],
            "AI-generated Security Testing test case (skill: Security Testing, evidence: evidenced)."
        );
        assert_eq!(request["category"], "Security Testing");
        assert_eq!(
            (request["priority"].as_str(), request["severity"].as_str()),
            (Some("HIGH"), Some("MAJOR"))
        );
        assert_eq!(request["preconditions"], json!(["A registered user"]));
        assert_eq!(
            request["steps"],
            json!([
                {"step_number": 1, "action": "Submit a 7-character password", "expected_result": "A validation error is shown"},
                {"step_number": 2, "action": "Submit an 8-character password", "expected_result": "The password is accepted"},
            ]),
            "steps are numbered from 1 in the order they are"
        );
        assert_eq!(
            request["expected_result"],
            "Only passwords of 8 characters or more are accepted"
        );
        assert_eq!(
            request["assertions"],
            json!(["Only passwords of 8 characters or more are accepted"])
        );
        assert_eq!(
            request["requirement_reference"], "FRD-2-01",
            "the requirement, when the draft names one"
        );
        assert_eq!(
            request["source_requirement"],
            "A password must be at least 8 characters long."
        );
        assert_eq!(request["source_document"], "FRD.md");
        assert_eq!(request["risk_factor"], "MEDIUM");
        assert!(
            request.get("suite_id").is_none(),
            "no suite unless the run made one"
        );
        let data: Value = serde_json::from_str(request["test_data"].as_str().unwrap()).unwrap();
        assert_eq!(
            data,
            json!({
                "skill_id": "skill-security-testing", "evidence": "evidenced", "source_reference": "at least 8 characters long",
                "requirement_id": "FRD-2-01", "technique": "negative",
            })
        );
    }

    #[test]
    fn the_tags_say_what_kind_of_case_it_is_where_it_came_from_and_which_run_and_place_it_has() {
        let request = case_request(&draft(json!({})), &info());
        assert_eq!(
            request["tags"],
            json!([
                "security-testing",
                "skill-security-testing",
                "evidenced",
                "ai-generated",
                "technique:negative",
                "autopilot:6f95ee30-3fc8-4bc6-9d6d-f8cb4c8ef988",
                "ap:6f95ee30:2:3",
            ])
        );
        // Without a technique there is no technique tag.
        let request = case_request(&draft(json!({"technique": null})), &info());
        let tags: Vec<&str> = request["tags"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t.as_str().unwrap())
            .collect();
        assert!(
            !tags.iter().any(|t| t.starts_with("technique:")),
            "{tags:?}"
        );
        assert_eq!(tags.len(), 6);
    }

    #[test]
    fn the_traceability_names_the_requirement_the_document_and_who_wrote_the_case() {
        let request = case_request(&draft(json!({})), &info());
        let t = &request["traceability"];
        assert_eq!(t["sourceDoc"], "FRD.md");
        assert_eq!(
            t["requirementRef"],
            "FRD-2-01 — cites: \"at least 8 characters long\""
        );
        assert_eq!(
            t["requirementText"],
            "A password must be at least 8 characters long."
        );
        assert_eq!(t["testCaseId"], "ap:6f95ee30:2:3");
        assert_eq!(t["testCategory"], "Security Testing");
        assert_eq!(
            t["aiAnalysis"],
            "Generated by ollama/qwen2.5:14b in autopilot run 6f95ee30-3fc8-4bc6-9d6d-f8cb4c8ef988 (skill: Security Testing) — evidence: evidenced, requirement: FRD-2-01, technique: negative, cites: \"at least 8 characters long\"."
        );
        for key in ["executionTarget", "evidencePolicy", "reportMapping"] {
            assert!(
                t[key].as_str().unwrap().starts_with("Not yet"),
                "{key}: {t}"
            );
        }
    }

    #[test]
    fn a_draft_that_names_no_requirement_is_referenced_by_its_quote_or_not_at_all() {
        let quoted = case_request(&draft(json!({"requirement_id": null})), &info());
        assert_eq!(
            quoted["requirement_reference"],
            "at least 8 characters long"
        );
        assert_eq!(
            quoted["traceability"]["requirementRef"],
            "at least 8 characters long"
        );
        let data: Value = serde_json::from_str(quoted["test_data"].as_str().unwrap()).unwrap();
        assert!(data.get("requirement_id").is_none());

        let bare = case_request(
            &draft(
                json!({"requirement_id": null, "source_reference": null, "evidence": "exploratory"}),
            ),
            &info(),
        );
        assert!(bare["requirement_reference"].is_null());
        assert_eq!(
            bare["traceability"]["requirementRef"],
            "Not cited (exploratory)"
        );
        assert_eq!(bare["tags"][2], "exploratory");
        let only_id = case_request(&draft(json!({"source_reference": null})), &info());
        assert_eq!(only_id["traceability"]["requirementRef"], "FRD-2-01");
    }

    #[test]
    fn what_the_run_does_not_know_is_left_out_not_invented() {
        let unknown = CaseInfo {
            skill_name: None,
            requirement_text: None,
            document: None,
            provider: None,
            model: None,
            ..info()
        };
        let request = case_request(&draft(json!({})), &unknown);
        assert!(
            request.get("source_document").is_none() && request.get("source_requirement").is_none()
        );
        assert_eq!(
            request["description"],
            "AI-generated Security Testing test case (skill: skill-security-testing, evidence: evidenced).",
            "the skill's id stands in for its name"
        );
        let t = &request["traceability"];
        assert_eq!(
            t["sourceDoc"],
            "Autopilot run (documents chosen when it was made)"
        );
        assert_eq!(t["requirementText"], "");
        let analysis = t["aiAnalysis"].as_str().unwrap();
        assert!(
            analysis
                .starts_with("Generated by an AI provider/an unreported model in autopilot run "),
            "{analysis}"
        );
        assert!(!analysis.contains("(skill:"), "{analysis}");
    }

    #[test]
    fn a_case_is_made_inside_the_runs_suite_when_it_has_one() {
        let suite = Uuid::new_v4();
        let request = case_request(
            &draft(json!({})),
            &CaseInfo {
                suite: Some(suite),
                ..info()
            },
        );
        assert_eq!(request["suite_id"], json!(suite));
    }

    #[test]
    fn the_risk_follows_the_priority() {
        let risk = |priority: &str| {
            case_request(&draft(json!({"priority": priority})), &info())["risk_factor"].clone()
        };
        assert_eq!(risk("CRITICAL"), "HIGH");
        assert_eq!(risk("HIGH"), "MEDIUM");
        assert_eq!(risk("MEDIUM"), "LOW");
        assert_eq!(risk("LOW"), "LOW");
    }

    #[test]
    fn the_category_tag_is_lower_case_with_dashes_between_words() {
        assert_eq!(category_tag("Security Testing"), "security-testing");
        assert_eq!(category_tag("  Edge   Case Testing "), "edge-case-testing");
        assert_eq!(category_tag("Functional"), "functional");
    }
}
